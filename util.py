import numpy as np


def bar_size_filter(Rthis : np.ndarray ,check_bins : int = 4) -> np.ndarray:
    lengthR=len(Rthis)
    for i in range(lengthR):
        if (i <1) or (i > lengthR-2) :
            continue 
        else:
            if Rthis[i-1]>1 and Rthis[i]<1 and Rthis[i+1]>1:
                Rthis[i]= (Rthis[i-1]+Rthis[i+1])/2 
    lessR=np.arange(lengthR)[Rthis<0.1]
    if len(lessR)>1:
        for i in range(len(lessR)):
            if i > 0:
                if lessR[i]-lessR[i-1] < check_bins+1:
                    Rthis[lessR[i-1]:lessR[i]]=0
            else:
                continue
                
                    
    return Rthis

